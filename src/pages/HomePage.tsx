const buildPolylinePath = (
  values: number[],
  width: number,
  height: number,
  padding: number,
) => {
  const maxValue = Math.max(1, ...values);
  return values
    .map((value, index) => {
      const x =
        values.length === 1
          ? width / 2
          : padding + (index * (width - padding * 2)) / (values.length - 1);
      const y = height - padding - (value / maxValue) * (height - padding * 2);
      return `${index === 0 ? 'M' : 'L'} ${x} ${y}`;
    })
    .join(' ');
};

const buildAreaPath = (
  values: number[],
  width: number,
  height: number,
  padding: number,
) => {
  const linePath = buildPolylinePath(values, width, height, padding);
  const endX = values.length === 1 ? width / 2 : width - padding;
  const startX = padding;
  return `${linePath} L ${endX} ${height - padding} L ${startX} ${height - padding} Z`;
};

const getDonutSegments = (
  items: Array<{ label: string; value: number }>,
  colors: string[],
) => {
  const total = items.reduce((sum, item) => sum + item.value, 0);
  let offset = 0;

  return items.map((item, index) => {
    const percentage = total ? (item.value / total) * 100 : 0;
    const segment = {
      ...item,
      color: colors[index % colors.length],
      percentage,
      strokeDasharray: `${percentage} ${100 - percentage}`,
      strokeDashoffset: 25 - offset,
    };
    offset += percentage;
    return segment;
  });
};

